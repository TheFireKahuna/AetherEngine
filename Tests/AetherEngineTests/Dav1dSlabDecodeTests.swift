/// AV1 decodes straight into the slabs the finisher reads. libdav1d allocates through the codec
/// context's `get_buffer2` and declares DR1 (FFmpegBuild's `libdav1d-get-buffer2` patch), so the
/// decoder installs `DecodeFrameAllocator` on it as on every other DR1 decoder, and a picture no
/// longer needs copying into a slab before the GPU pass. The slab layout has to meet libdav1d's
/// contract (64-byte plane starts and linesizes, one chroma linesize), or the decoder refuses it.
///
/// The stream is three temporal units of SVT-AV1 at 128x72, 10-bit 4:2:0, with film grain, which
/// libdav1d applies into a second picture of its own allocation.
struct Dav1dSlabDecodeTests {

    private struct Decode {
        var planes: [[UInt8]] = []
        var inSlabs = 0
        var error: Int32 = 0
    }

    private static func decode(allocator: DecodeFrameAllocator?, threads: Int32) throws -> Decode {
        let codec = try #require(avcodec_find_decoder_by_name("libdav1d"))
        #expect(codec.pointee.capabilities & Int32(AV_CODEC_CAP_DR1) != 0, "libdav1d declares DR1")
        var context = avcodec_alloc_context3(codec)
        defer { avcodec_free_context(&context) }
        let ctx = try #require(context)
        ctx.pointee.thread_count = threads
        allocator?.install(on: ctx)
        try #require(avcodec_open2(ctx, codec, nil) >= 0)

        var packet = av_packet_alloc()
        var frame = av_frame_alloc()
        defer { av_packet_free(&packet); av_frame_free(&frame) }
        var result = Decode()

        func drain() {
            while avcodec_receive_frame(ctx, frame) >= 0 {
                result.planes.append(packed(frame!))
                if let allocator, allocator.slab(of: frame!) != nil { result.inSlabs += 1 }
                av_frame_unref(frame)
            }
        }
        for unit in temporalUnits {
            try #require(av_new_packet(packet, Int32(unit.count)) >= 0)
            unit.withUnsafeBytes { _ = memcpy(packet!.pointee.data, $0.baseAddress!, unit.count) }
            let sent = avcodec_send_packet(ctx, packet)
            av_packet_unref(packet)
            if sent < 0 { result.error = sent; return result }
            drain()
        }
        _ = avcodec_send_packet(ctx, nil)
        drain()
        return result
    }

    /// The visible picture, rows packed without padding, all planes in order.
    private static func packed(_ frame: UnsafeMutablePointer<AVFrame>) -> [UInt8] {
        let format = AVPixelFormat(rawValue: frame.pointee.format)
        let width = frame.pointee.width, height = frame.pointee.height
        let size = av_image_get_buffer_size(format, width, height, 1)
        var out = [UInt8](repeating: 0, count: Int(size))
        let copied = out.withUnsafeMutableBufferPointer { dst in
            withUnsafePointer(to: &frame.pointee.data) { data in
                data.withMemoryRebound(to: UnsafePointer<UInt8>?.self, capacity: 8) { data in
                    withUnsafePointer(to: &frame.pointee.linesize) { linesize in
                        linesize.withMemoryRebound(to: Int32.self, capacity: 8) { linesize in
                            av_image_copy_to_buffer(dst.baseAddress, size, data, linesize, format, width, height, 1)
                        }
                    }
                }
            }
        }
        return copied == size ? out : []
    }

    @Test("every AV1 picture lands in a slab, and equals libdav1d's own decode", arguments: [Int32(1), 4])
    func picturesInSlabs(threads: Int32) throws {
        let allocator = try #require(DecodeFrameAllocator(), "needs a Metal device")
        let own = try Self.decode(allocator: nil, threads: threads)
        let slabs = try Self.decode(allocator: allocator, threads: threads)
        #expect(own.error == 0 && slabs.error == 0)
        #expect(slabs.planes.count == 3)
        #expect(slabs.inSlabs == slabs.planes.count, "no picture needed a copy")
        #expect(slabs.planes == own.planes, "the same pictures, bit for bit")
    }

