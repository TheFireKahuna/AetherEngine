    private static func open(_ data: Data) throws -> Demuxer {
        let demuxer = Demuxer()
        try demuxer.open(reader: DataIOReader(data: data),
                         profile: .subtitleSideDemuxer(callerProbesize: nil, callerMaxAnalyzeDuration: nil))
        return demuxer
    }

    private static func index(_ data: Data, demuxer: Demuxer) throws -> MP4SampleIndex {
        try MP4SampleIndex.read(demuxer: demuxer, streams: AetherEngine.indexedSubtitleStreams(of: demuxer),
                                videoTracks: AetherEngine.indexedVideoTracks(of: demuxer),
                                source: IOReaderByteSource(DataIOReader(data: data)), token: .forParserTests)
    }

    /// Every subtitle packet the walk reads, per stream: time, duration and bytes.
    private static func walked(_ data: Data) throws -> [Int32: [(pts: Int64, duration: Int64, payload: [UInt8])]] {
        let demuxer = try open(data)
        defer { demuxer.close() }
        let subtitles = demuxer.subtitleStreamIndices()
        demuxer.discardAllStreamsExcept(subtitles)
        var out: [Int32: [(pts: Int64, duration: Int64, payload: [UInt8])]] = [:]
        while let packet = try demuxer.readPacket() {
            defer { var p: UnsafeMutablePointer<AVPacket>? = packet; trackedPacketFree(&p) }
            let p = packet.pointee
            guard subtitles.contains(p.stream_index) else { continue }
            out[p.stream_index, default: []].append(
                (p.pts, p.duration, Array(UnsafeBufferPointer(start: p.data, count: Int(p.size)))))
        }
        return out
    }

    @Test("every subtitle sample read from the index is the packet the walk gets, an empty edit included")
    func samplesAreThePackets() throws {
        let demuxer = try Self.open(Self.movText)
        defer { demuxer.close() }
        let index = try Self.index(Self.movText, demuxer: demuxer)
        let walked = try Self.walked(Self.movText)
        let source = IOReaderByteSource(DataIOReader(data: Self.movText))
        let streams = AetherEngine.indexedSubtitleStreams(of: demuxer)
        let tracks = index.trackNumbers(for: streams)
        #expect(tracks == [1: 2, 2: 3])
        for stream in streams {
            let track = try #require(tracks[stream.streamIndex])
            #expect(index.isComplete(track: track, frameCount: nil))
            let frames = try index.blocks(track: track).map { try #require(index.readFrame($0, track: track, from: source)) }
            let packets = try #require(walked[stream.streamIndex])
            #expect(frames.map(\.ticks) == packets.map(\.pts))
            #expect(frames.map(\.durationTicks) == packets.map(\.duration))
            #expect(frames.map(\.payload) == packets.map(\.payload))
        }
        // The German track sits behind the empty edit: its first sample plays at 0.75 s, as the walk has it.
        #expect(index.blocks(track: 3).first.map { index.seconds(ticks: $0.ticks, track: 3) } == 0.75)
        #expect(index.subtitleTracks.map(\.language) == ["eng", "ger"])
    }

    @Test("a track the edit list cuts is not trusted; the other one is")
    func cutTrackIsIncomplete() throws {
        let demuxer = try Self.open(Self.movTextCut)
        defer { demuxer.close() }
        let index = try Self.index(Self.movTextCut, demuxer: demuxer)
        #expect(!index.isComplete(track: 2, frameCount: nil))
        #expect(index.isComplete(track: 3, frameCount: nil))
    }

    /// Its `moov` lists no samples; each `moof` lists its own as the stream is read, so no subtitle
    /// track is ever whole, while each keyframe entry the demuxer has is its sample.
    @Test("a fragmented file's subtitles are not complete, and the keyframes it lists read as their packets")
    func fragmentedSubtitlesAreIncomplete() throws {
        let demuxer = try Self.open(Self.movTextFragmented)
        defer { demuxer.close() }
        let index = try Self.index(Self.movTextFragmented, demuxer: demuxer)
        for track in index.subtitleTracks { #expect(!index.isComplete(track: track.number, frameCount: nil)) }
        let source = IOReaderByteSource(DataIOReader(data: Self.movTextFragmented))
        for entry in demuxer.indexedKeyframeEntries(streamIndex: demuxer.videoStreamIndex) {
            #expect(index.readKeyframe(track: 1, position: entry.pos, ticks: entry.pts, from: source) != nil)
        }
    }

    /// The registry reads an MP4's index off the demuxer, and the forward prefetch then stores from it
    /// exactly what its walk stores.
    @Test("the prefetch from an MP4's index stores what its walk stores")
    func prefetchFromTheIndex() async throws {
        let demuxer = try Self.open(Self.movText)
        defer { demuxer.close() }
        let reader = DataIOReader(data: Self.movText)
        let cache = SourceByteCache(directory: FileManager.default.temporaryDirectory
            .appending(path: "mp4-index-\(UUID().uuidString)", directoryHint: .isDirectory), budget: .fixed(0),
            removesDirectory: true)
        let outcome = await SourceIndexRegistry(cache: cache).index(
            of: URL(string: "https://media.example.com/a.mp4")!, headers: [:], demuxer: demuxer, through: reader)
        let index = try #require(outcome.index)
        let subtitles = demuxer.subtitleStreamIndices()
        let plan = SubtitleForwardPrefetcher.IndexSource.plan(
            index: index, listed: AetherEngine.indexedSubtitleStreams(of: demuxer), streams: subtitles)
        #expect(plan.refused.isEmpty, "\(plan.refused)")
        let fromIndex = SubtitlePacketStore()
        let indexSource = SubtitleForwardPrefetcher.IndexSource(
            index: index, bytes: IOReaderByteSource(reader, closesReader: false), streams: plan.streams,
            assemblyIndices: [], from: 0)
        while case .harvested = try indexSource.step(into: fromIndex) {}

        let walker = try Self.open(Self.movText)
        defer { walker.close() }
        walker.discardAllStreamsExcept(subtitles)
        let fromWalk = SubtitlePacketStore()
        let walkSource = SubtitleForwardPrefetcher.DemuxerSource(
            demuxer: walker, streamIndices: subtitles, assemblyIndices: [], pacingIndex: -1)
        while try walkSource.step(into: fromWalk) != .endOfFile {}

        for stream in subtitles.sorted() {
            let a = fromIndex.entries(streamIndex: stream, from: 0, through: 20)
            let b = fromWalk.entries(streamIndex: stream, from: 0, through: 20)
            #expect(!a.isEmpty)
            #expect(a.map(\.payload) == b.map(\.payload))
            #expect(a.map(\.ptsSeconds) == b.map(\.ptsSeconds))
            #expect(a.map(\.durationSeconds) == b.map(\.durationSeconds))
        }
    }
