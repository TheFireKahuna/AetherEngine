/// A decoder behind the overlay's clock catches up on pictures nobody will see: the late ones are not converted,
/// those nothing references are not decoded, and a chain that counts consecutive pictures (the deinterlacer's
/// window, inverse telecine) is not handed them at all and starts over on the first picture that is on time.
/// Whatever it skipped, the pictures it shows after the catch-up are the ones a decode that never fell behind
/// showed, at the same timestamps.
struct SoftwareDecoderCatchUpTests {

    struct Case: CustomTestStringConvertible, Sendable {
        let name: String
        let fixture: String
        let config: DeinterlaceConfig
        var testDescription: String { name }
    }

    static let cases: [Case] = [
        Case(name: "interlaced at field rate", fixture: interlacedBase64, config: DeinterlaceConfig(fieldRate: .field)),
        Case(name: "interlaced at frame rate", fixture: interlacedBase64, config: DeinterlaceConfig(fieldRate: .frame)),
        Case(name: "3:2 telecine, inverse telecined", fixture: telecineBase64,
             config: DeinterlaceConfig(fieldRate: .frame, film: .pulldown32)),
    ]

    /// Late from 0.6 s, back on time at 1.4 s; the chain has settled again within this much after it.
    static let lateFrom = 0.6, onTime = 1.4, settle = 0.25

    @Test("after a catch-up the decoder shows exactly the pictures a decode that never fell behind showed",
          arguments: cases)
    func catchUpRejoinsTheContinuousDecode(_ c: Case) throws {
        let continuous = try Self.decode(c, catchingUp: false)
        let caughtUp = try Self.decode(c, catchingUp: true)
        try #require(continuous.count > 40, "\(continuous.count) pictures")
        // Up to the clip's last pulldown cycle: inverse telecine restarted on a different cycle phase ends a stream
        // on a different partial cycle, so its final pictures can differ there and nowhere else.
        let rejoined = Self.onTime + Self.settle, lastCycle = (continuous.last ?? 0) - Self.settle
        let window = { (t: Double) in t >= rejoined && t < lastCycle }
        #expect(caughtUp.filter(window) == continuous.filter(window), "from \(rejoined) s on, timestamps and count")
        // Pictures still inside the decoder when it fell behind are late too and are not shown; the rest are as before.
        #expect(Set(caughtUp.filter { $0 < Self.lateFrom }).isSubset(of: continuous),
                "before the catch-up, only pictures the continuous decode showed")
        #expect(!caughtUp.contains { $0 >= Self.lateFrom + Self.settle && $0 < Self.onTime },
                "nothing late is shown")
    }

    /// The presentation times of every picture the decoder delivers, in seconds. Catching up, the packets between
    /// `lateFrom` and `onTime` are fed the way the overlay tap feeds a decoder behind its clock.
    private static func decode(_ c: Case, catchingUp: Bool) throws -> [Double] {
        let data = try #require(Data(base64Encoded: c.fixture, options: .ignoreUnknownCharacters))
        let demuxer = Demuxer()
        try demuxer.open(reader: DataIOReader(data: data), formatHint: "mp4")
        defer { demuxer.close() }
        let stream = try #require(demuxer.stream(at: demuxer.videoStreamIndex))
        let timeBase = stream.pointee.time_base
        let collector = Collector()
        let decoder = SoftwareVideoDecoder()
        decoder.deinterlaceConfig = c.config
        try decoder.open(stream: stream) { _, pts, _ in collector.append(pts.seconds) }
        defer { decoder.close() }
        while let pkt = try? demuxer.readPacket() {
            defer { var p: UnsafeMutablePointer<AVPacket>? = pkt; trackedPacketFree(&p) }
            guard pkt.pointee.stream_index == demuxer.videoStreamIndex else { continue }
            let seconds = Double(pkt.pointee.pts) * av_q2d(timeBase)
            let late = catchingUp && seconds >= lateFrom && seconds < onTime
            if late { decoder.skipUntilPTS = CMTime(seconds: onTime, preferredTimescale: 90_000) }
            decoder.discardsNonReferencePictures(late)
            decoder.decode(packet: pkt)
        }
        decoder.drainForEndOfStream()
        return collector.values.map { ($0 * 1000).rounded() / 1000 }
    }

    private final class Collector: @unchecked Sendable {
        private let lock = NSLock()
        private var storage: [Double] = []
        func append(_ value: Double) { lock.withLock { storage.append(value) } }
        var values: [Double] { lock.withLock { storage.sorted() } }
    }

